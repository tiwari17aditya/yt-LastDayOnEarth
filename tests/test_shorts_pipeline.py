def test_pipeline_shorts_degradation_boundary(tmp_path):
    """Verifies that an unexpected failure in Shorts generation NEVER breaks the main video pipeline."""
    from src.processor.shorts_generator import ShortsGenerator
    from src.exceptions import VideoProcessingError

    gen = ShortsGenerator(output_dir=tmp_path)
    mock_video = tmp_path / "main.mp4"
    mock_video.write_bytes(b"mock data")

    # Force generate_short to raise an unexpected exception
    with patch.object(
        gen,
        "generate_short",
        side_effect=VideoProcessingError(
            operation="render_short",
            root_cause="Out of memory",
            recovery_action="Check memory",
        ),
    ):
        degraded = False
        try:
            gen.extract_and_render_companion_short(source_video_path=mock_video)
        except Exception as e:
            # Main pipeline catches this and records DEGRADED
            degraded = True
            assert isinstance(e, VideoProcessingError)
        assert degraded is True
