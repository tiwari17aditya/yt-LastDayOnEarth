def test_shorts_generator_extract_and_render_mock(tmp_path):
    gen = ShortsGenerator(output_dir=tmp_path)
    source_video = tmp_path / "rendered_long_form.mp4"
    source_video.write_bytes(b"dummy video bytes")

    events = [
        DummyEvent(description="Frenzy Giant ambush and death", start_time=45.0),
    ]

    mock_generate = MagicMock(return_value=tmp_path / "short_ep147_rendered_long_form.mp4")
    with patch.object(gen, "generate_short", mock_generate):
        short_path, viral_meta = gen.extract_and_render_companion_short(
            source_video_path=source_video,
            events=events,
            episode_number=147,
            duration=30.0,
        )

        assert viral_meta["hook_type"] == "fail_panic"
        assert viral_meta["start_time"] == 45.0
        assert mock_generate.called
        call_kwargs = mock_generate.call_args[1]
        assert call_kwargs["start_time"] == 45.0
        assert call_kwargs["duration"] == 30.0
        assert call_kwargs["episode_number"] == 147
        assert short_path == tmp_path / "short_ep147_rendered_long_form.mp4"


