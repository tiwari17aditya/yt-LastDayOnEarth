    assert meta.privacy_status == "private"  # publish_at requires private
    assert meta.publish_at == "2026-11-26T21:30:00Z"
    assert "https://youtu.be/SD5SqkxL3yI" in meta.description
    assert "Episode #147" in meta.description
    assert "https://www.youtube.com/playlist?list=PLxyz" in meta.description
    assert any("Shorts" in t for t in meta.tags)


